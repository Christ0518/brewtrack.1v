BEGIN;

DO $$
DECLARE
  id_data_type text;
  is_identity_column text;
  id_default text;
  id_sequence text;
  max_id bigint;
BEGIN
  SELECT data_type, is_identity, column_default
  INTO id_data_type, is_identity_column, id_default
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'tbl_category'
    AND column_name = 'id';

  IF id_data_type IS NULL THEN
    RAISE EXCEPTION 'Column public.tbl_category.id was not found';
  END IF;

  IF id_data_type NOT IN ('smallint', 'integer', 'bigint') THEN
    RAISE EXCEPTION 'public.tbl_category.id must be a smallint, integer, or bigint to generate IDs (found %)', id_data_type;
  END IF;

  IF is_identity_column <> 'YES' AND id_default IS NULL THEN
    ALTER TABLE public.tbl_category
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;

  id_sequence := pg_get_serial_sequence('public.tbl_category', 'id');
  IF id_sequence IS NULL THEN
    RAISE EXCEPTION 'public.tbl_category.id has no owned sequence after enabling ID generation';
  END IF;

  SELECT MAX(id)::bigint INTO max_id FROM public.tbl_category;

  IF max_id IS NULL THEN
    PERFORM setval(id_sequence::regclass, 1, false);
  ELSE
    PERFORM setval(id_sequence::regclass, GREATEST(max_id, 1), max_id >= 1);
  END IF;
END
$$;

COMMIT;
