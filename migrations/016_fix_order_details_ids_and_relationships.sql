    ALTER TABLE public.tbl_orders_details
      ADD CONSTRAINT tbl_orders_details_order_id_fkey
      FOREIGN KEY (order_id)
      REFERENCES public.tbl_orders(id);
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.tbl_orders_details'::regclass
      AND conname = 'tbl_orders_details_variant_id_fkey'
  ) THEN
    ALTER TABLE public.tbl_orders_details
