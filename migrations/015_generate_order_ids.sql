BEGIN;

DO $$
DECLARE
  id_data_type text;
  is_identity_column text;
  id_sequence text;
  max_id bigint;
BEGIN
  SELECT data_type, is_identity
  INTO id_data_type, is_identity_column
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'tbl_orders'
    AND column_name = 'id';

  IF id_data_type IS NULL THEN
    RAISE EXCEPTION 'Column public.tbl_orders.id was not found';
  END IF;

  IF id_data_type NOT IN ('smallint', 'integer', 'bigint') THEN
    RAISE EXCEPTION
      'public.tbl_orders.id must be an integer type to generate IDs (found %)',
      id_data_type;
  END IF;

  IF is_identity_column <> 'YES' THEN
    EXECUTE 'ALTER TABLE public.tbl_orders ALTER COLUMN id DROP DEFAULT';
    EXECUTE 'ALTER TABLE public.tbl_orders ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY';
  END IF;

  id_sequence := pg_get_serial_sequence('public.tbl_orders', 'id');
  IF id_sequence IS NULL THEN
    RAISE EXCEPTION 'Could not create an identity sequence for public.tbl_orders.id';
  END IF;

  SELECT MAX(id)::bigint INTO max_id FROM public.tbl_orders;

  IF max_id IS NULL THEN
    PERFORM setval(id_sequence::regclass, 1, false);
  ELSE
    PERFORM setval(id_sequence::regclass, GREATEST(max_id, 1), max_id >= 1);
  END IF;
END
$$;

COMMIT;
