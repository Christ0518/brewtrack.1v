BEGIN;

DO $$
DECLARE
  current_table text;
  id_data_type text;
  is_identity_column text;
  id_sequence text;
  max_id bigint;
BEGIN
  FOREACH current_table IN ARRAY ARRAY['ingredient_batches', 'tbl_inventory']
  LOOP
    SELECT data_type, is_identity
    INTO id_data_type, is_identity_column
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND information_schema.columns.table_name = current_table
      AND column_name = 'id';

    IF id_data_type IS NULL THEN
      RAISE EXCEPTION 'Column public.%.id was not found', current_table;
    END IF;

    IF id_data_type NOT IN ('smallint', 'integer', 'bigint') THEN
      RAISE EXCEPTION 'public.%.id must be an integer type to generate IDs (found %)', current_table, id_data_type;
    END IF;

    IF is_identity_column <> 'YES' THEN
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id DROP DEFAULT', current_table);
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', current_table);
    END IF;

    id_sequence := pg_get_serial_sequence(format('public.%I', current_table), 'id');

    IF id_sequence IS NULL THEN
      RAISE EXCEPTION 'Could not create an identity sequence for public.%.id', current_table;
    END IF;

    EXECUTE format('SELECT MAX(id)::bigint FROM public.%I', current_table)
      INTO max_id;

    IF max_id IS NULL THEN
      PERFORM setval(id_sequence::regclass, 1, false);
    ELSE
      PERFORM setval(id_sequence::regclass, GREATEST(max_id, 1), max_id >= 1);
    END IF;
  END LOOP;
END
$$;

COMMIT;
