BEGIN;

DO $$
DECLARE
  id_data_type text;
  is_identity_column text;
  id_default text;
  id_sequence text;
  max_id bigint;
BEGIN
  SELECT data_type, is_identity, column_default
  INTO id_data_type, is_identity_column, id_default
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'tbl_inventory'
    AND column_name = 'id';

  IF id_data_type IS NULL THEN
    RAISE EXCEPTION 'Column public.tbl_inventory.id was not found';
  END IF;

  IF id_data_type NOT IN ('smallint', 'integer', 'bigint') THEN
    RAISE EXCEPTION 'public.tbl_inventory.id must be a smallint, integer, or bigint to generate IDs (found %)', id_data_type;
  END IF;

  IF is_identity_column <> 'YES' AND id_default IS NULL THEN
    ALTER TABLE public.tbl_inventory
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;

  id_sequence := pg_get_serial_sequence('public.tbl_inventory', 'id');
  IF id_sequence IS NOT NULL THEN
    SELECT MAX(id)::bigint INTO max_id FROM public.tbl_inventory;

    IF max_id IS NULL THEN
      PERFORM setval(id_sequence::regclass, 1, false);
    ELSE
      PERFORM setval(id_sequence::regclass, GREATEST(max_id, 1), max_id >= 1);
    END IF;
  END IF;
END
$$;

INSERT INTO public.tbl_inventory (ingredient_id, quantity, minimum_stock)
SELECT ingredients.id, 0, NULL
FROM public.tbl_ingredients AS ingredients
WHERE ingredients.shop_id = 1
  AND ingredients.is_deleted = 0
  AND NOT EXISTS (
    SELECT 1
    FROM public.tbl_inventory AS inventory
    WHERE inventory.ingredient_id = ingredients.id
  );

COMMIT;
